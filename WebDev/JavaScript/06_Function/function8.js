// Date Function or object 

const d=new Date();
console.log(d);

// Date have many function 
console.log("Today's Date = ",d.getDate()); // today's Date
console.log("Today's Day = ",d.getDay());
console.log("Today's Month = ",d.getMonth());
console.log("Today's Year = ",d.getFullYear());
console.log("Today's Hours = ",d.getHours());
console.log("Today's Timezone Offset = ",d.getTimezoneOffset());


