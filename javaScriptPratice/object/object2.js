// Mutability and Immutability in JS

// in the bellow code we can update the x value this is called Mutable
let x = 99;
console.log(x);
x = 100;
console.log(x);


// If we want to make Immutable we can initialize the value with const

const y = 99;
console.log(y);

// y = 100; // it will give  error

// with const we have to assign value while declaration it
